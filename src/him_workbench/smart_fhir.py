"""Live SMART on FHIR connection to a public sandbox. Synthetic test patients only, read-only.

Standalone SMART App Launch: the browser is sent to the sandbox's own authorization endpoint
with PKCE (S256), and the sandbox lets the user pick one of its own synthetic test patients.
The authorization and token endpoints are never hardcoded — they're read at connect time from
the FHIR server's own `.well-known/smart-configuration`, the way a real client is supposed to,
since a sandbox's exact endpoint paths are its own to define and can change.

Default sandbox: SMART Health IT's public one (https://launch.smarthealthit.org/v/r4/fhir).
It needs no app registration — any client_id string is accepted. Override with HIM_SMART_ISS /
HIM_SMART_CLIENT_ID for a different sandbox (e.g. one that does require a registered client_id).

This module never writes to the FHIR server — GET only, nothing else.
"""

from __future__ import annotations

import base64
import hashlib
import json
import os
import secrets
import urllib.error
import urllib.parse
import urllib.request

from .chart import Chart, chart_from_resources
from .fhir import patient_from_fhir
from .matching import Patient

# This launcher (SMART Launcher v2, which launch.smarthealthit.org runs) does not treat a plain
# "/v/r4/fhir" base as a valid standalone-launch server on its own: the launch context — patient,
# provider, whether it's a standalone or EHR launch, PKCE requirement, etc. — has to be baked into
# the FHIR base URL itself as a "/sim/<base64url-encoded 17-element JSON array>/" path segment.
# This exact one was generated by the launcher's own "Standalone Launch" form (confirmed live
# against the real sandbox, not guessed): decoded, it's
# [launch_type=3 (patient-standalone), patient="", provider="", encounter="AUTO", skip_login=0,
#  skip_auth=0, sim_ehr=0, scope="", redirect_uris="", client_id="", client_secret="",
#  auth_error="", jwks_url="", jwks="", client_type=0, pkce=1, fhir_server=""]
# — i.e. no patient pre-selected (the sandbox prompts you to pick one), standalone (not EHR), and
# PKCE required. Override with HIM_SMART_ISS for a different sandbox or a different sim config.
DEFAULT_ISS = "https://launch.smarthealthit.org/v/r4/sim/WzMsIiIsIiIsIkFVVE8iLDAsMCwwLCIiLCIiLCIiLCIiLCIiLCIiLCIiLDAsMSwiIl0/fhir"
DEFAULT_CLIENT_ID = "him-workbench"
DEFAULT_SCOPE = ("launch/patient openid fhirUser patient/Patient.read patient/Condition.read "
                 "patient/MedicationRequest.read patient/AllergyIntolerance.read "
                 "patient/Observation.read patient/Encounter.read patient/Immunization.read")
# Resource types pulled into the chart, beyond Patient itself — same categories chart.py already
# reads from a local Synthea bundle, just fetched live instead of from a file.
RESOURCE_TYPES = ("Condition", "MedicationRequest", "AllergyIntolerance", "Observation",
                  "Encounter", "Immunization")


class SmartError(Exception):
    """A step of the SMART launch or a live FHIR read failed. Always carries a plain-English reason;
    never silently returns partial/guessed data."""


def iss() -> str:
    return os.environ.get("HIM_SMART_ISS", DEFAULT_ISS).rstrip("/")


def client_id() -> str:
    return os.environ.get("HIM_SMART_CLIENT_ID", DEFAULT_CLIENT_ID)


def _get_json(url: str, token: str | None = None, timeout: int = 15) -> dict:
    headers = {"Accept": "application/fhir+json, application/json"}
    if token:
        headers["Authorization"] = f"Bearer {token}"
    req = urllib.request.Request(url, headers=headers)
    try:
        with urllib.request.urlopen(req, timeout=timeout) as r:
            return json.loads(r.read())
    except urllib.error.HTTPError as exc:
        raise SmartError(f"{url} returned HTTP {exc.code}") from exc
    except (urllib.error.URLError, TimeoutError) as exc:
        raise SmartError(f"could not reach {url}: {exc}") from exc
    except json.JSONDecodeError as exc:
        raise SmartError(f"{url} did not return valid JSON: {exc}") from exc


def discover(server: str) -> dict:
    """{authorization_endpoint, token_endpoint}, read from the server's own smart-configuration —
    never hardcoded, since that's the one part of this flow a sandbox fully controls itself."""
    conf = _get_json(server.rstrip("/") + "/.well-known/smart-configuration")
    auth, token = conf.get("authorization_endpoint"), conf.get("token_endpoint")
    if not auth or not token:
        raise SmartError("this FHIR server's smart-configuration has no authorization_endpoint/"
                         "token_endpoint — it may not support SMART App Launch")
    return {"authorization_endpoint": auth, "token_endpoint": token}


def new_pkce() -> tuple[str, str]:
    """(code_verifier, code_challenge) for PKCE S256, per RFC 7636."""
    verifier = base64.urlsafe_b64encode(secrets.token_bytes(32)).rstrip(b"=").decode()
    challenge = base64.urlsafe_b64encode(hashlib.sha256(verifier.encode()).digest()).rstrip(b"=").decode()
    return verifier, challenge


def authorize_url(authorization_endpoint: str, *, server: str, cid: str, redirect_uri: str,
                  state: str, code_challenge: str, scope: str = DEFAULT_SCOPE) -> str:
    params = {"response_type": "code", "client_id": cid, "redirect_uri": redirect_uri, "scope": scope,
             "state": state, "aud": server, "code_challenge": code_challenge, "code_challenge_method": "S256"}
    return authorization_endpoint + "?" + urllib.parse.urlencode(params)


def _post_form(url: str, fields: dict, timeout: int = 15) -> dict:
    body = urllib.parse.urlencode(fields).encode()
    req = urllib.request.Request(url, data=body, headers={"Content-Type": "application/x-www-form-urlencoded",
                                                           "Accept": "application/json"})
    try:
        with urllib.request.urlopen(req, timeout=timeout) as r:
            return json.loads(r.read())
    except urllib.error.HTTPError as exc:
        detail = exc.read().decode(errors="replace")[:300]
        raise SmartError(f"the sandbox refused the token exchange: HTTP {exc.code} {detail}") from exc
    except (urllib.error.URLError, TimeoutError) as exc:
        raise SmartError(f"could not reach the token endpoint: {exc}") from exc
    except json.JSONDecodeError as exc:
        raise SmartError(f"the token endpoint did not return valid JSON: {exc}") from exc


def exchange_code(token_endpoint: str, *, code: str, redirect_uri: str, cid: str, code_verifier: str,
                  timeout: int = 15) -> dict:
    """POST the authorization code for a token. Returns the token response as given (access_token,
    patient, scope, expires_in, ...) — callers decide what they need from it."""
    return _post_form(token_endpoint, {"grant_type": "authorization_code", "code": code,
                                       "redirect_uri": redirect_uri, "client_id": cid,
                                       "code_verifier": code_verifier}, timeout=timeout)


def fetch_chart(server: str, patient_id: str, token: str) -> tuple[Patient | None, Chart]:
    """Read-only live fetch of one patient's chart from the connected FHIR server, built through the
    same chart_from_resources() used for a local Synthea bundle — only where the resources come from
    differs. Raises SmartError on any failed read; never returns a partial chart silently."""
    base = server.rstrip("/")
    pres = _get_json(f"{base}/Patient/{patient_id}", token)
    patient, _ = patient_from_fhir(pres)
    resources = [pres]
    for rtype in RESOURCE_TYPES:
        bundle = _get_json(f"{base}/{rtype}?patient={patient_id}&_count=200", token)
        resources += [e["resource"] for e in bundle.get("entry") or []
                     if isinstance(e, dict) and isinstance(e.get("resource"), dict)]
    return patient, chart_from_resources(resources, patient_id=patient_id)
